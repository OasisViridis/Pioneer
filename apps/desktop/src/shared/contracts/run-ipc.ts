import { z } from 'zod';

import {
  EGRESS_MATERIAL_LIMIT,
  EgressMaterialSchema,
  type ListRunMaterialsRequest,
  type ListRunMaterialsReply,
} from './egress';
import {
  RunCursorRequestSchema,
  RunEventSchema,
  RunIdentitySchema,
  RunStatusSchema,
  type RunStartRequest,
  type RunStopRequest,
  type RunCursorRequest,
} from './pioneer-run';

/** Fixed run protocol surface (P2 run contract §2). No arbitrary channels. */
export const RUN_IPC_CHANNELS = {
  authorize: 'run:authorize',
  start: 'run:start',
  stop: 'run:stop',
  get: 'run:get',
  subscribe: 'run:subscribe',
  ack: 'run:ack',
  unsubscribe: 'run:unsubscribe',
  events: 'run:events',
  materials: 'run:materials',
} as const;

export const RUN_ADMISSION_CODES = [
  'INVALID_REQUEST',
  'UNTRUSTED_SENDER',
  'BINDING_MISMATCH',
  'STALE_REVISION',
  'REQUEST_CONFLICT',
  'AUTHORIZATION_REQUIRED',
  'RUN_ACTIVE',
  'CAPACITY_EXCEEDED',
  'JOURNAL_UNAVAILABLE',
] as const;

export const RUN_STOP_CODES = [
  'INVALID_REQUEST',
  'UNTRUSTED_SENDER',
  'BINDING_MISMATCH',
  'RUN_NOT_FOUND',
] as const;

export const RunAuthorizeRequestSchema = z
  .object({
    sessionId: RunIdentitySchema.shape.sessionId,
    projectId: RunIdentitySchema.shape.projectId,
    expectedRevision: RunIdentitySchema.shape.revision,
    /** The task text itself is the egress material; main computes its digest. */
    task: z.string().min(1).max(16_384),
    /** Explicit file materials whose content may be sent to the model. */
    materials: z.array(z.string().min(1).max(1024)).max(EGRESS_MATERIAL_LIMIT),
  })
  .strict();

/** Authorization summary is generated by main from its own records only. */
export const RunAuthorizationSummarySchema = z
  .object({
    grantId: RunIdentitySchema.shape.runId,
    taskDigest: z.string().min(1).max(512),
    projectName: z.string().min(1).max(512),
    tools: z.array(z.enum(['read_file', 'list_directory', 'search_in_files'])),
    adapter: z.enum(['controlled', 'pi']),
    model: z.string().min(1).max(256).nullable(),
    expiresAt: z.iso.datetime(),
    materials: z.array(EgressMaterialSchema).max(EGRESS_MATERIAL_LIMIT),
  })
  .strict();

export const RunAuthorizeReplySchema = z.discriminatedUnion('ok', [
  z
    .object({
      ok: z.literal(true),
      summary: RunAuthorizationSummarySchema,
    })
    .strict(),
  z
    .object({
      ok: z.literal(false),
      code: z.enum(RUN_ADMISSION_CODES),
    })
    .strict(),
]);

export const RunStartReplySchema = z.discriminatedUnion('ok', [
  z
    .object({ ok: z.literal(true), runId: RunIdentitySchema.shape.runId })
    .strict(),
  z
    .object({ ok: z.literal(false), code: z.enum(RUN_ADMISSION_CODES) })
    .strict(),
]);

export const RunStopReplySchema = z.discriminatedUnion('ok', [
  z.object({ ok: z.literal(true), status: RunStatusSchema }).strict(),
  z.object({ ok: z.literal(false), code: z.enum(RUN_STOP_CODES) }).strict(),
]);

/** Snapshot page delivered by getRun and by push batches (contract §2/§5). */
export const RunPageSchema = z
  .object({
    identity: RunIdentitySchema,
    status: RunStatusSchema,
    lastSeq: z.number().int().nonnegative(),
    oldestSeq: z.number().int().nonnegative(),
    gap: z.boolean(),
    events: z.array(RunEventSchema).max(32),
    nextAfterSeq: z.number().int().nonnegative(),
    hasMore: z.boolean(),
  })
  .strict();

export const RunGetReplySchema = z.discriminatedUnion('ok', [
  z.object({ ok: z.literal(true), page: RunPageSchema }).strict(),
  z.object({ ok: z.literal(false), code: z.literal('RUN_NOT_FOUND') }).strict(),
]);

export const RunSubscribeReplySchema = z.discriminatedUnion('ok', [
  z.object({ ok: z.literal(true) }).strict(),
  z.object({ ok: z.literal(false), code: z.literal('RUN_NOT_FOUND') }).strict(),
]);

export const RunEventBatchSchema = z
  .object({
    page: RunPageSchema,
  })
  .strict();

export const RunAckRequestSchema = RunCursorRequestSchema;
export const RunUnsubscribeRequestSchema = RunIdentitySchema;

export type RunAuthorizeRequest = z.infer<typeof RunAuthorizeRequestSchema>;
export type RunAuthorizationSummary = z.infer<
  typeof RunAuthorizationSummarySchema
>;
export type RunAuthorizeReply = z.infer<typeof RunAuthorizeReplySchema>;
export type RunStartReply = z.infer<typeof RunStartReplySchema>;
export type RunStopReply = z.infer<typeof RunStopReplySchema>;
export type RunPage = z.infer<typeof RunPageSchema>;
export type RunEventBatch = z.infer<typeof RunEventBatchSchema>;
export type RunGetReply = z.infer<typeof RunGetReplySchema>;

/** Fixed renderer port. It grants no direct adapter, Node, or file access. */
export interface RunDesktopApi {
  authorizeRun(request: RunAuthorizeRequest): Promise<RunAuthorizeReply>;
  listRunMaterials(
    request: ListRunMaterialsRequest,
  ): Promise<ListRunMaterialsReply>;
  startRun(request: RunStartRequest): Promise<RunStartReply>;
  stopRun(request: RunStopRequest): Promise<RunStopReply>;
  getRun(request: RunCursorRequest): Promise<RunPage | null>;
  subscribeRun(request: RunCursorRequest): Promise<boolean>;
  acknowledgeRunPage(request: RunCursorRequest): Promise<void>;
  unsubscribeRun(
    request: z.infer<typeof RunUnsubscribeRequestSchema>,
  ): Promise<void>;
  onRunEventBatch(callback: (batch: RunEventBatch) => void): () => void;
}
